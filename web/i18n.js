  var TBL = { en: EN, ja: JA };
  var LANG = "ko";

  function T(s, v) {
    var d = TBL[LANG];
    var out = (d && d[s]) || s;
    if (v) out = out.replace(/\{(\w+)\}/g, function (m, k) { return k in v ? String(v[k]) : m; });
    return out;
  }

  function applyStatic() {
    document.querySelectorAll("[data-t]").forEach(function (el) { el.textContent = T(el.getAttribute("data-t") || el.textContent); });
    document.querySelectorAll("[data-t-title]").forEach(function (el) { el.title = T(el.getAttribute("data-t-title")); });
    document.querySelectorAll("[data-t-placeholder]").forEach(function (el) { el.placeholder = T(el.getAttribute("data-t-placeholder")); });
    document.title = T("만화 제작기");
  }

  /** `data-t` 에 값이 없으면 지금 글을 키로 삼는다 — HTML 에 한국어를 그대로 두고 표시만 붙이면 된다 */
  function seedKeys() {
    document.querySelectorAll("[data-t]").forEach(function (el) {
      if (!el.getAttribute("data-t")) el.setAttribute("data-t", el.textContent.trim());
    });
  }

  window.T = T;
  window.mangaLang = function () { return LANG; };
  window.setMangaLang = function (l) {
    LANG = TBL[l] ? l : "ko";
    document.documentElement.lang = LANG;
    applyStatic();
  };
  /** ★한국어에서도 한 번 돌린다 — `data-t-title`·`data-t-placeholder` 는 HTML 에 값이 없어서
   *  여기서 채워야 비로소 붙는다 (안 돌리면 한국어에서만 툴팁·안내글이 통째로 빠진다). */
  function start() { seedKeys(); applyStatic(); }
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", start);
  else start();
